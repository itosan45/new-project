/**
 * 使える道具と、その状態。
 *
 * 「Figmaが使えます」と書く前に、実際に繋がっているかを確かめる。
 * 繋がっていても、席（権限）が足りなくて書き込めないことがある。
 *
 * 状態は変わるので、確認日を必ず持たせる。
 * 日付の無い「使えます」は、いつの話か分からず信用できない。
 */

export type ToolState =
  /** 繋がっていて、実際に使える */
  | "使える"
  /** 繋がっているが、権限が足りない */
  | "権限が足りない"
  /** 認証がまだ */
  | "認証がまだ"
  /** そもそも繋いでいない */
  | "未接続";

