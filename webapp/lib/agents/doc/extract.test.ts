import assert from "node:assert/strict";
import test from "node:test";
import {
  キーワードで探す,
  区分を選ぶ,
  項目を取り出す,
  金額を探す,
  日付を探す,
  電話番号を探す,
} from "@/lib/agents/doc/extract";

/**
 * 抽出規則の検証。
 *
 * ケースは `ocr-excel/テスト.py` と同じもの。
 * 同じ規則が Python と TypeScript の2か所にあるので、
 * 片方だけ直したときにここで落ちるようにしてある。
 */

test("西暦の日付を取り出せる", () => {
  assert.equal(日付を探す("2026年8月12日 領収書"), "2026-08-12");
  assert.equal(日付を探す("発行日 2026/8/5"), "2026-08-05");
  assert.equal(日付を探す("2026-12-31"), "2026-12-31");
});

test("令和の日付を西暦に直せる", () => {
  assert.equal(日付を探す("令和8年8月12日"), "2026-08-12");
});

test("日付がなければ空", () => {
  assert.equal(日付を探す("ただの文章です"), "");
});

test("ありえない月日は拾わない", () => {
  assert.equal(日付を探す("2026年13月45日"), "");
});

test("電話番号を日付と間違えない", () => {
  // 0532-11-2222 を 0532年11月22日として読んでいた。実際に起きた
  assert.equal(日付を探す("TEL 0532-11-2222"), "");
  assert.equal(
    日付を探す("調査日 令和8年8月14日\nTEL 0532-11-2222"),
    "2026-08-14",
    "電話番号が先に当たって、本物の日付を取り逃している",
  );
});

test("整理番号のような数字を日付にしない", () => {
  assert.equal(日付を探す("管理番号 0001-02-03"), "");
});

test("金額を取り出せる", () => {
  assert.equal(金額を探す("合計 ¥12,300"), "12300");
  assert.equal(金額を探す("1,500円"), "1500");
});

test("複数の金額なら一番大きいものを返す", () => {
  // 合計額であることが多い
  assert.equal(金額を探す("小計 1,000円\n消費税 100円\n合計 1,100円"), "1100");
});

test("電話番号を取り出せる", () => {
  assert.equal(電話番号を探す("TEL 03-1234-5678"), "03-1234-5678");
  assert.equal(電話番号を探す("090-1111-2222まで"), "090-1111-2222");
});

test("キーワードの右側を拾える", () => {
  assert.equal(キーワードで探す("宛名: 山田太郎", ["宛名"]), "山田太郎");
});

test("宛名の敬称を落とす", () => {
  assert.equal(キーワードで探す("宛名: 山田太郎 様", ["宛名"]), "山田太郎");
  assert.equal(キーワードで探す("宛名\n株式会社ABC 御中", ["宛名"]), "株式会社ABC");
});

test("キーワードの次の行を拾える", () => {
  assert.equal(キーワードで探す("お名前\n佐藤花子", ["お名前"]), "佐藤花子");
});

// --- 区分を選ぶ --------------------------------------------------------------

test("手がかりに当たる区分を返す", () => {
  const 区分一覧 = [
    { label: "配送", clues: ["配送", "届かな"] },
    { label: "返品", clues: ["返品", "返金"] },
  ];
  assert.equal(区分を選ぶ("商品が届きません", 区分一覧), "");
  assert.equal(区分を選ぶ("商品が届かないです", 区分一覧), "配送");
  assert.equal(区分を選ぶ("返金してほしいです", 区分一覧), "返品");
});

test("どれにも当たらなければ空。fallbackを指定すればそれを返す", () => {
  const 区分一覧 = [{ label: "最優先", clues: ["至急"] }];
  assert.equal(区分を選ぶ("お世話になっております", 区分一覧), "");
  assert.equal(区分を選ぶ("お世話になっております", 区分一覧, "通常"), "通常");
  assert.equal(区分を選ぶ("至急ご確認ください", 区分一覧, "通常"), "最優先");
});

test("区分は定義した順で最初に一致したものを採る", () => {
  // 同じ本文に複数区分の手がかりが同時に出ても、実行するたびに結果が
  // 変わってはいけない。定義順を機械的に固定する
  const 区分一覧 = [
    { label: "返品", clues: ["返品"] },
    { label: "品質", clues: ["荒れ"] },
  ];
  assert.equal(区分を選ぶ("返品したいです。肌が荒れました", 区分一覧), "返品");
});

// --- 項目を取り出す ----------------------------------------------------------

test("項目を取り出すは kind に応じて正しい関数を呼ぶ", () => {
  assert.equal(
    項目を取り出す({ field: "調査日", hint: "", required: true, kind: "日付" }, "2026年8月14日"),
    "2026-08-14",
  );
  assert.equal(
    項目を取り出す(
      { field: "区分", hint: "", required: true, kind: "区分", categories: [{ label: "A", clues: ["a"] }] },
      "aです",
    ),
    "A",
  );
  assert.equal(
    項目を取り出す({ field: "名前", hint: "", required: true, kind: "ファイル名" }, "全文", "台帳.txt"),
    "台帳.txt",
  );
  assert.equal(
    項目を取り出す({ field: "不明", hint: "", required: true }, "何か書いてある"),
    "",
    "kind が無い項目は推測せず空で返す",
  );
});
