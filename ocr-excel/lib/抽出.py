"""読み取った文字から、日付・金額などの項目を取り出す処理。

Vision APIに依存しないので、この部分だけ単体でテストできる。
"""

import re

# 2026/8/12, 2026-08-12, 2026年8月12日, R8.8.12 など
_日付パターン = [
    re.compile(r"(\d{4})\s*[/\-年]\s*(\d{1,2})\s*[/\-月]\s*(\d{1,2})\s*日?"),
    re.compile(r"令和\s*(\d{1,2})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日"),
]

# ¥1,234 / 1,234円 / 金額 1234 など。小数は扱わない(日本円想定)
_金額パターン = re.compile(r"[¥￥]\s*([0-9][0-9,]*)|([0-9][0-9,]*)\s*円")

# 03-1234-5678 / 090-1234-5678 / 0312345678 など
_電話パターン = re.compile(r"0\d{1,4}[-(）\s]?\d{1,4}[-)）\s]?\d{3,4}")


def 日付を探す(文字列: str) -> str:
    """最初に見つかった日付を YYYY-MM-DD の形で返す。無ければ空文字。"""
    for i, パターン in enumerate(_日付パターン):
        m = パターン.search(文字列)
        if not m:
            continue
        年, 月, 日 = (int(x) for x in m.groups())
        if i == 1:  # 令和 → 西暦
            年 += 2018
        if not (1 <= 月 <= 12 and 1 <= 日 <= 31):
            continue
        return f"{年:04d}-{月:02d}-{日:02d}"
    return ""


def 金額を探す(文字列: str) -> str:
    """見つかった金額のうち一番大きいものを返す。合計額であることが多いため。"""
    金額一覧 = []
    for m in _金額パターン.finditer(文字列):
        数字 = m.group(1) or m.group(2)
        try:
            金額一覧.append(int(数字.replace(",", "")))
        except ValueError:
            continue
    return str(max(金額一覧)) if 金額一覧 else ""


def 電話番号を探す(文字列: str) -> str:
    m = _電話パターン.search(文字列)
    return m.group(0).strip() if m else ""


def キーワードで探す(文字列: str, 手がかり一覧: list[str]) -> str:
    """手がかりの言葉の右側、または次の行にある値を返す。

    「宛名: 山田太郎」も「宛名\n山田太郎」も拾えるようにする。
    """
    行一覧 = [行.strip() for 行 in 文字列.splitlines()]
    for i, 行 in enumerate(行一覧):
        for 手がかり in 手がかり一覧:
            if 手がかり not in 行:
                continue
            # 同じ行の、手がかりより右側
            右側 = 行.split(手がかり, 1)[1].strip(" :：　|｜")
            if 右側:
                return _敬称を落とす(右側)
            # 空なら次の行
            if i + 1 < len(行一覧) and 行一覧[i + 1]:
                return _敬称を落とす(行一覧[i + 1])
    return ""


def _敬称を落とす(値: str) -> str:
    """末尾の「様」「さん」「御中」などを取り除く。宛名として使いやすくするため。"""
    for 敬称 in ("様", "さま", "サマ", "さん", "御中", "殿"):
        if 値.endswith(敬称):
            return 値[: -len(敬称)].strip()
    return 値


def 一件ぶんを抽出する(全文: str, ファイル名: str, 項目設定: list[dict]) -> dict:
    """設定に従って、1枚ぶんの値を {列: 値} の形で返す。"""
    結果 = {}
    for 項目 in 項目設定:
        種類 = 項目["種類"]
        if 種類 == "ファイル名":
            値 = ファイル名
        elif 種類 == "日付":
            値 = 日付を探す(全文)
        elif 種類 == "金額":
            値 = 金額を探す(全文)
        elif 種類 == "電話番号":
            値 = 電話番号を探す(全文)
        elif 種類 == "全文":
            値 = 全文
        elif 種類 == "キーワード":
            値 = キーワードで探す(全文, 項目.get("手がかり", []))
        else:
            値 = ""
        結果[項目["列"]] = 値
    return 結果
